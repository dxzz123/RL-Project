"""Online rollout ADP using explicit future simulation under a base policy.

This controller does not fit a value function offline. At each dispatch it
compares a small set of complete feasible plans, using exact current profit
plus sampled remaining-horizon profit under service-first. The base plan is
included. Future draws are shared across candidates and independent of the
live environment's random generator. Finite sampling and the restricted set
of plans mean that improvement over the base policy is not guaranteed.
"""
import argparse
from dataclasses import asdict, dataclass
import hashlib
import json
from numbers import Integral, Real
from pathlib import Path
import time

import numpy as np

from ..benchmarks.evaluation import evaluate_policy
from ..benchmarks.policies import dispatch_outcome, fixed_prices, service_first_dispatch
from ..benchmarks.scalable import coordinate_inventory_dispatch
from ..config import Scenario
from ..simulator import DispatchAction, Mode
from .fitted_train import _new_run_directory
from .fitted_value import sample_dispatch_observation

MAX_CANDIDATE_PLANS = 16
MAX_FUTURE_QUERIES_PER_DECISION = 50_000
MAX_ROLLOUT_SAMPLES = 256
ENERGY_ROUNDOFF_KWH = 1e-8
_SOURCE_FILES = ('rl/rollout_adp.py', 'rl/fitted_value.py', 'rl/fitted_train.py',
    'benchmarks/policies.py', 'benchmarks/scalable.py', 'benchmarks/evaluation.py',
    'simulator.py', 'choice.py', 'config.py')


def _integer(value, name, minimum=0):
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral) or value < minimum:
        raise ValueError(f'{name} must be an integer >= {minimum}')


def _real(value, name, *, minimum=0., maximum=None):
    if (isinstance(value, (bool, np.bool_)) or not isinstance(value, Real)
            or not np.isfinite(value) or value < minimum
            or (maximum is not None and value > maximum)):
        raise ValueError(f'Invalid {name}')


@dataclass(frozen=True)
class RolloutADPConfig:
    seed: int = 7
    rollout_samples: int = 8
    price_index: int | None = None
    base_recharge_threshold: float = .2
    alternative_recharge_thresholds: tuple = (.4, .6)
    inventory_early_shadow: float = .3
    inventory_late_shadow: float = .15
    planner_sweeps: int = 2
    energy_fractions: tuple = (1.,)

    def resolved_price_index(self, scenario):
        return scenario.n_price_levels//2 if self.price_index is None else int(self.price_index)

    def validate(self, scenario, *, extra_proposal=False):
        scenario.validate()
        _integer(self.seed, 'seed')
        _integer(self.rollout_samples, 'rollout_samples', 1)
        _integer(self.planner_sweeps, 'planner_sweeps', 1)
        if self.rollout_samples > MAX_ROLLOUT_SAMPLES or self.planner_sweeps > 16:
            raise ValueError('Rollout sample or coordinate-sweep budget exceeded')
        if self.price_index is not None:
            _integer(self.price_index, 'price_index')
        if self.resolved_price_index(scenario) >= scenario.n_price_levels:
            raise ValueError('price_index is outside this scenario')
        _real(self.base_recharge_threshold, 'base_recharge_threshold', maximum=1.)
        for threshold in self.alternative_recharge_thresholds:
            _real(threshold, 'alternative_recharge_threshold', maximum=1.)
        for name in ('inventory_early_shadow', 'inventory_late_shadow'):
            _real(getattr(self, name), name)
        fractions = np.asarray(self.energy_fractions)
        if (fractions.ndim != 1 or not len(fractions) or fractions.dtype.kind not in 'iuf'
                or len(fractions) > 16 or not np.isfinite(fractions).all()
                or (fractions < 0).any() or (fractions > 1).any()):
            raise ValueError('energy_fractions must be a nonempty finite sequence in [0,1]')
        plans = 3+len(self.alternative_recharge_thresholds)+int(extra_proposal)
        if plans > MAX_CANDIDATE_PLANS:
            raise ValueError('Rollout candidate-plan budget exceeded')
        if plans*self.rollout_samples*(scenario.horizon-1) > MAX_FUTURE_QUERIES_PER_DECISION:
            raise ValueError('Rollout future-query budget exceeded')
        return self


class RolloutADPPolicy:
    """Compare complete plans using remaining-horizon base-policy rollouts.

    Call ``reset_episode(episode_key)`` before every episode. The evaluation
    helper does this automatically. The key is an identifier, not a simulator
    random state; future simulator seeds are generated by a separate local RNG.
    An optional ``extra_proposal(obs)`` may add one feasible action list. It is
    only a candidate generator and never supplies continuation values.
    """
    def __init__(self, scenario, config=None, *, extra_proposal=None):
        if extra_proposal is not None and not callable(extra_proposal):
            raise ValueError('extra_proposal must be callable or None')
        self.scenario = scenario.validate()
        self.config = (config or RolloutADPConfig()).validate(scenario,
            extra_proposal=extra_proposal is not None)
        self.extra_proposal = extra_proposal
        self.decisions = []
        self.statistics = dict(decisions=0, candidate_plans=0, current_plan_outcomes=0,
            future_model_queries=0, exogenous_draws=0, coordinate_candidate_outcomes=0,
            boundary_roundoff_corrections=0, max_boundary_roundoff_kwh=0.)
        self.reset_episode(0)

    def reset_episode(self, episode_key=0, action_seed=None):
        """Replayable planning randomness, independent of environmental draws."""
        _integer(episode_key, 'episode_key')
        if action_seed is not None:
            _integer(action_seed, 'action_seed')
        self.episode_key = int(episode_key)
        self.episode_decision = 0
        self._rng = np.random.default_rng(np.random.SeedSequence(
            [int(self.config.seed), self.episode_key, 0x524F4C4C]))

    def prices(self, obs, rng=None):
        return fixed_prices(obs, self.scenario, self.config.resolved_price_index(self.scenario))

    def _validated_actions(self, obs, actions):
        if not isinstance(actions, (list, tuple)) or len(actions) != self.scenario.n_mcv:
            raise ValueError('A candidate must provide one DispatchAction per vehicle')
        result = []
        for vehicle, action in enumerate(actions):
            if not isinstance(action, DispatchAction):
                raise ValueError('Candidate entries must be DispatchAction objects')
            _integer(action.mode, 'mode')
            _integer(action.target_zone, 'target_zone')
            _real(action.energy_kwh, 'energy_kwh')
            if (action.mode >= len(Mode) or action.target_zone >= self.scenario.n_zones
                    or not obs['action_mask'][vehicle, action.mode, action.target_zone]):
                raise ValueError('Candidate contains a physically infeasible action')
            result.append(action)
        return result

    def _candidate_plans(self, obs):
        c, scenario = self.config, self.scenario
        period = int(obs['period'][0])
        statistics = {}
        plans = [('service_first_base', service_first_dispatch(obs, scenario, c.base_recharge_threshold)),
            ('inventory', coordinate_inventory_dispatch(obs, scenario,
                c.inventory_early_shadow if period < scenario.horizon//2 else c.inventory_late_shadow,
                sweeps=c.planner_sweeps, energy_fractions=c.energy_fractions, diagnostics=statistics)),
            ('current_profit', coordinate_inventory_dispatch(obs, scenario, 0.,
                sweeps=c.planner_sweeps, energy_fractions=c.energy_fractions, diagnostics=statistics))]
        plans += [(f'service_first_{threshold:g}', service_first_dispatch(obs, scenario, threshold))
                  for threshold in c.alternative_recharge_thresholds]
        if self.extra_proposal is not None:
            plans.append(('extra_proposal', self.extra_proposal(obs)))
        names, commands, seen = [], [], set()
        for name, actions in plans:
            actions = self._validated_actions(obs, actions)
            key = tuple((int(a.mode), int(a.target_zone), float(a.energy_kwh)) for a in actions)
            if key not in seen:
                names.append(name)
                commands.append(actions)
                seen.add(key)
        return names, commands, statistics

    def _clip_roundoff(self, energies):
        scenario = self.scenario
        clipped = np.clip(energies, scenario.reserve_kwh, scenario.battery_capacity_kwh)
        difference = np.abs(clipped-energies)
        if not np.isfinite(difference).all() or np.any(difference > ENERGY_ROUNDOFF_KWH):
            raise ValueError('Rollout transition violates physical battery bounds')
        self.statistics['boundary_roundoff_corrections'] += int(np.count_nonzero(difference))
        self.statistics['max_boundary_roundoff_kwh'] = max(
            self.statistics['max_boundary_roundoff_kwh'], float(difference.max()))
        return clipped

    def dispatch(self, obs, rng=None):
        started = time.perf_counter()
        scenario, config = self.scenario, self.config
        period = np.asarray(obs['period'])
        if (int(obs['stage']) != 1 or period.shape != (1,) or period.dtype.kind not in 'iu'
                or not 0 <= period[0] < scenario.horizon):
            raise ValueError('Rollout dispatch needs a valid current dispatch observation')
        period = int(period[0])
        names, plans, coordinate_stats = self._candidate_plans(obs)
        remaining = scenario.horizon-period-1
        query_budget = len(plans)*config.rollout_samples*remaining
        if query_budget > MAX_FUTURE_QUERIES_PER_DECISION:
            raise ValueError('Actual rollout query budget exceeded')
        # Even model-query seeds are separate from conventional odd evaluation
        # banks. Each current decision uses a newly drawn table, shared by all
        # candidate plans; no live simulator or its future draws are accessed.
        seed_shape = (remaining, config.rollout_samples)
        seeds = 2*self._rng.integers(0, np.iinfo(np.int64).max//2, size=seed_shape, dtype=np.int64)
        while len(np.unique(seeds)) != seeds.size:
            seeds = 2*self._rng.integers(0, np.iinfo(np.int64).max//2, size=seed_shape, dtype=np.int64)
        outcomes = [dispatch_outcome(obs, scenario, actions) for actions in plans]
        scores = np.repeat(np.asarray([o['reward'] for o in outcomes])[:, None], config.rollout_samples, axis=1)
        completed = 0
        for candidate, outcome in enumerate(outcomes):
            for draw in range(config.rollout_samples):
                locations, energies = outcome['next_locations'], outcome['next_energy_kwh']
                discount = scenario.discount_per_period
                for offset, future_period in enumerate(range(period+1, scenario.horizon)):
                    energies = self._clip_roundoff(energies)
                    future = sample_dispatch_observation(scenario, future_period, locations, energies,
                        int(seeds[offset, draw]), config.resolved_price_index(scenario))
                    actions = self._validated_actions(future, service_first_dispatch(future, scenario,
                        config.base_recharge_threshold))
                    step = dispatch_outcome(future, scenario, actions)
                    scores[candidate, draw] += discount*step['reward']
                    discount *= scenario.discount_per_period
                    locations, energies = step['next_locations'], step['next_energy_kwh']
                    completed += 1
        if completed != query_budget or not np.isfinite(scores).all():
            raise FloatingPointError('Rollout query count or value is invalid')
        means = scores.mean(axis=1)
        winner = int(np.argmax(means))
        self.statistics['decisions'] += 1
        self.statistics['candidate_plans'] += len(plans)
        self.statistics['current_plan_outcomes'] += len(plans)
        self.statistics['future_model_queries'] += completed
        self.statistics['exogenous_draws'] += int(seeds.size)
        self.statistics['coordinate_candidate_outcomes'] += coordinate_stats['candidate_outcomes']
        self.decisions.append(dict(episode_key=self.episode_key, episode_decision=self.episode_decision,
            period=period, candidates=names, selected=names[winner], current_profit=[o['reward'] for o in outcomes],
            mean_total_scores=means.tolist(), sampled_total_scores=scores.tolist(),
            future_periods=list(range(period+1, scenario.horizon)), future_draw_seeds=seeds.tolist(),
            future_model_queries=completed, query_budget=query_budget,
            coordinate_candidate_outcomes=coordinate_stats['candidate_outcomes'],
            seconds=time.perf_counter()-started))
        self.episode_decision += 1
        return plans[winner]

    def provenance(self):
        package = Path(__file__).resolve().parents[1]
        return dict(schema='charging_env.rollout_adp.v1', algorithm='online_policy_rollout_adp',
            offline_training=False, learned_value_bootstrap=False, scenario=asdict(self.scenario),
            config=asdict(self.config), fixed_price_index=self.config.resolved_price_index(self.scenario),
            base_policy='service_first', horizon='all remaining physical periods',
            reward='original business profit including every cost and terminal inventory payment',
            planning_rng='Local SeedSequence([config.seed, episode_key, 0x524F4C4C]); reset per episode',
            common_random_numbers='One future-period/draw seed table shared across current candidates',
            extra_proposal=self.extra_proposal is not None, statistics=dict(self.statistics),
            candidate_limit=MAX_CANDIDATE_PLANS, future_query_limit=MAX_FUTURE_QUERIES_PER_DECISION,
            rollout_sample_limit=MAX_ROLLOUT_SAMPLES,
            source_sha256={'src/charging_env/'+name: hashlib.sha256((package/name).read_bytes()).hexdigest()
                           for name in _SOURCE_FILES})


def evaluate_rollout_policy(policy, seeds, *, action_seed=6999, label='rollout_adp'):
    """Evaluate with deterministic episode resets, keeping a complete plan trace."""
    result = evaluate_policy(policy.scenario, seeds, policy.prices, policy.dispatch,
        action_seed=action_seed, label=label, on_episode_start=policy.reset_episode)
    if result['invalid_actions']:
        raise RuntimeError('Rollout evaluation produced invalid physical actions')
    result['planning_statistics'] = dict(policy.statistics)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scenario', type=Path)
    parser.add_argument('--seed', type=int, default=7, help='Planning randomness; there is no offline training')
    parser.add_argument('--price-index', type=int, default=None)
    parser.add_argument('--episodes', type=int, default=16)
    parser.add_argument('--eval-seed-base', type=int, default=1_000_001)
    parser.add_argument('--rollout-samples', type=int, default=8)
    parser.add_argument('--base-recharge-threshold', type=float, default=.2)
    parser.add_argument('--inventory-early-shadow', type=float, default=.3)
    parser.add_argument('--inventory-late-shadow', type=float, default=.15)
    parser.add_argument('--planner-sweeps', type=int, default=2)
    parser.add_argument('--output-dir', type=Path, default=Path('outputs/rollout_adp'))
    args = parser.parse_args(argv)
    try:
        _integer(args.episodes, 'episodes', 1)
        _integer(args.eval_seed_base, 'eval_seed_base')
        scenario = Scenario.from_json(args.scenario) if args.scenario else Scenario()
        config = RolloutADPConfig(seed=args.seed, price_index=args.price_index,
            rollout_samples=args.rollout_samples, base_recharge_threshold=args.base_recharge_threshold,
            inventory_early_shadow=args.inventory_early_shadow, inventory_late_shadow=args.inventory_late_shadow,
            planner_sweeps=args.planner_sweeps).validate(scenario)
    except (ValueError, TypeError, OSError) as exc:
        parser.error(str(exc))
    policy = RolloutADPPolicy(scenario, config)
    directory = _new_run_directory(args.output_dir)
    seeds = [args.eval_seed_base+2*i for i in range(args.episodes)]
    protocol = policy.provenance() | dict(evaluation_seeds=seeds, action_seed=6999)
    (directory/'protocol.json').write_text(json.dumps(protocol, indent=2, allow_nan=False)+'\n')
    print(f'Online rollout ADP: no offline fit. Outputs: {directory}', flush=True)
    started = time.perf_counter()
    result = evaluate_rollout_policy(policy, seeds)
    if policy.provenance()['source_sha256'] != protocol['source_sha256']:
        raise RuntimeError('Rollout source changed during evaluation')
    for filename, value in (('evaluation.json', result), ('planning_trace.json', policy.decisions),
                            ('provenance.json', policy.provenance())):
        (directory/filename).write_text(json.dumps(value, indent=2, allow_nan=False)+'\n')
    summary = {key: result[key] for key in ('n_episodes', 'mean_discounted_profit', 'confidence_interval_95',
        'mean_unmet_mobile_kwh', 'mean_final_inventory_kwh', 'mean_policy_decision_ms',
        'invalid_actions', 'action_counts', 'planning_statistics')}
    summary.update(offline_training=False, wall_seconds=time.perf_counter()-started,
        evaluation_sha256=hashlib.sha256((directory/'evaluation.json').read_bytes()).hexdigest(),
        protocol_sha256=hashlib.sha256((directory/'protocol.json').read_bytes()).hexdigest())
    (directory/'summary.json').write_text(json.dumps(summary, indent=2, allow_nan=False)+'\n')
    print(json.dumps(summary, indent=2, allow_nan=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
